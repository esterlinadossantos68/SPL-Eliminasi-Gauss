import numpy as np

# ==========================================
# FUNGSI ELIMINASI GAUSS
# ==========================================

def eliminasi_gauss(A, B):

    # Mengubah data menjadi array bertipe float
    A = np.array(A, dtype=float)
    B = np.array(B, dtype=float).reshape(-1, 1)

    # Membentuk matriks augmented [A | B]
    M = np.hstack((A, B))

    # Menentukan jumlah variabel
    n = len(B)

    # ======================================
    # PROSES ELIMINASI GAUSS
    # ======================================

    for i in range(n):

        # Jika pivot bernilai nol
        if abs(M[i][i]) < 1e-12:

            # Mencari baris untuk ditukar
            for k in range(i + 1, n):

                if abs(M[k][i]) > 1e-12:
                    M[[i, k]] = M[[k, i]]
                    break

            else:
                raise ValueError(
                    "Sistem tidak memiliki solusi tunggal."
                )

        # Mengubah elemen di bawah pivot menjadi nol
        for k in range(i + 1, n):

            faktor = M[k][i] / M[i][i]

            for j in range(i, n + 1):
                M[k][j] = M[k][j] - faktor * M[i][j]

    # ======================================
    # SUBSTITUSI MUNDUR
    # ======================================

    x = np.zeros(n)

    for i in range(n - 1, -1, -1):

        jumlah = 0

        for j in range(i + 1, n):
            jumlah += M[i][j] * x[j]

        x[i] = (M[i][n] - jumlah) / M[i][i]

    return M, x


# ==========================================
# CONTOH SISTEM PERSAMAAN LINEAR
# ==========================================

# 2x + y - z = 8
# -3x - y + 2z = -11
# -2x + y + 2z = -3

A = [
    [2, 1, -1],
    [-3, -1, 2],
    [-2, 1, 2]
]

B = [8, -11, -3]


# ==========================================
# MENJALANKAN ALGORITMA
# ==========================================

matriks_akhir, solusi = eliminasi_gauss(A, B)


# ==========================================
# MENAMPILKAN HASIL
# ==========================================

print("Matriks setelah proses Eliminasi Gauss:")
print(np.round(matriks_akhir, 3))

print("\nHasil Penyelesaian SPL:")

for i, nilai in enumerate(solusi):
    print(f"x{i+1} = {nilai:.3f}")